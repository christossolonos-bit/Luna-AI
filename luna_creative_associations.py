creative_associations_system: Optional[LunaCreativeAssociations] = None

def initialize_creative_associations(ollama_chat_func) -> LunaCreativeAssociations:
    """Initialize creative associations system"""
    global creative_associations_system
    if creative_associations_system is None:
        creative_associations_system = LunaCreativeAssociations(ollama_chat_func)
    return creative_associations_system

def get_creative_associations() -> Optional[LunaCreativeAssociations]:
    """Get creative associations system instance"""
    return creative_associations_system

def generate_creative_idea(problem: str, context: str = "general") -> Optional[CreativeIdea]:
    """Generate a creative idea"""
    if creative_associations_system:
        return creative_associations_system.generate_creative_idea(problem, context)
    return None

def generate_lateral_thinking_response(user_input: str, context: str = "general") -> str:
    """Generate a response using lateral thinking"""
    if creative_associations_system:
        idea = creative_associations_system.generate_creative_idea(user_input, context)
        if idea:
            return idea.idea_content
    return ""

