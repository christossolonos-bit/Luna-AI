class AssociationType(Enum):
    """Types of creative associations"""
    DIRECT = "direct"                    # A → B (obvious)
    ANALOGICAL = "analogical"            # A is like B
    REMOTE = "remote"                    # A ⟹ B (distant)
    LATERAL = "lateral"                  # A ⊥ B (perpendicular)
    BISOCIATIVE = "bisociative"         # A ∩ B (intersection)
    BLENDED = "blended"                  # A + B = C (new concept)
    SERENDIPITOUS = "serendipitous"     # A ? B (unexpected)

class CreativityLevel(Enum):
    """Creativity levels"""
    CONVENTIONAL = "conventional"        # 0.0-0.3
    NOVEL = "novel"                     # 0.3-0.6
    CREATIVE = "creative"               # 0.6-0.8
    HIGHLY_CREATIVE = "highly_creative" # 0.8-0.95
    REVOLUTIONARY = "revolutionary"      # 0.95-1.0

@dataclass
class ConceptNode:
    """A concept in the creative association network"""
    concept_id: str
    concept: str
    domain: str
    activation: float  # 0.0 to 1.0
    novelty: float  # 0.0 to 1.0
    utility: float  # 0.0 to 1.0
    timestamp: float

@dataclass
class CreativeAssociation:
    """An association between concepts"""
    association_id: str
    concept_a: str
    concept_b: str
    association_type: AssociationType
    strength: float  # 0.0 to 1.0
    novelty: float  # 0.0 to 1.0
    utility: float  # 0.0 to 1.0
    creativity_score: float  # Combined score
    context: str
    timestamp: float
    reinforcement_count: int = 0
    last_reinforcement: Optional[float] = None

@dataclass
class CreativeIdea:
    """A creative idea generated by Luna"""
    idea_id: str
    idea_content: str
    source_concepts: List[str]
    association_path: List[str]
    creativity_level: CreativityLevel
    novelty_score: float
    utility_score: float
    originality_score: float
    timestamp: float

