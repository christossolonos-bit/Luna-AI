    def _assess_idea_novelty(self, idea: str) -> float:
        """Assess how novel an idea is"""
        # Check if similar ideas already exist
        novelty = 0.8  # Base novelty
        
        for existing_idea in self.creative_ideas:
            # Simple similarity check
            idea_words = set(idea.lower().split())
            existing_words = set(existing_idea.idea_content.lower().split())
            
            overlap = len(idea_words.intersection(existing_words))
            similarity = overlap / max(len(idea_words), len(existing_words))
            
            if similarity > 0.5:
                novelty *= 0.7  # Reduce novelty if similar idea exists
        
        return max(0.1, min(1.0, novelty))
    
    def _assess_idea_utility(self, idea: str, problem: str) -> float:
        """Assess how useful an idea is"""
        # Check if idea addresses the problem
        problem_words = set(problem.lower().split())
        idea_words = set(idea.lower().split())
        
        relevance = len(problem_words.intersection(idea_words)) / max(len(problem_words), 1)
        
        # Base utility on relevance and length
        utility = relevance * 0.7 + min(1.0, len(idea) / 200.0) * 0.3
        
        return max(0.1, min(1.0, utility))
    
    def _assess_idea_originality(self, idea: str, associations: List[CreativeAssociation]) -> float:
        """Assess how original an idea is"""
        # Higher originality if uses more remote/lateral associations
        if not associations:
            return 0.5
        
        originality_scores = []
        for assoc in associations:
            type_originality = {
                AssociationType.DIRECT: 0.1,
                AssociationType.ANALOGICAL: 0.4,
                AssociationType.REMOTE: 0.7,
                AssociationType.LATERAL: 0.85,
                AssociationType.BISOCIATIVE: 0.9,
                AssociationType.BLENDED: 0.95,
                AssociationType.SERENDIPITOUS: 1.0
            }
            originality_scores.append(type_originality.get(assoc.association_type, 0.5))
        
        return np.mean(originality_scores)
    
    def _determine_creativity_level(self, creativity_score: float) -> CreativityLevel:
        """Determine creativity level from score"""
        if creativity_score >= 0.95:
            return CreativityLevel.REVOLUTIONARY
        elif creativity_score >= 0.8:
            return CreativityLevel.HIGHLY_CREATIVE
        elif creativity_score >= 0.6:
            return CreativityLevel.CREATIVE
        elif creativity_score >= 0.3:
            return CreativityLevel.NOVEL
        else:
            return CreativityLevel.CONVENTIONAL
    
    def reinforce_creative_association(self, association_id: str, reward: float):
        """Reinforce a creative association (RL for creativity)"""
        try:
            if association_id not in self.associations:
                return False
            
            assoc = self.associations[association_id]
            
            # Update with reinforcement learning
            old_creativity = assoc.creativity_score
            
            # Reward increases creativity score
            assoc.creativity_score = min(1.0, assoc.creativity_score + reward * 0.1)
            assoc.strength = min(1.0, assoc.strength + reward * 0.15)
            assoc.reinforcement_count += 1
            assoc.last_reinforcement = time.time()
            
            # Store reward
            self.association_rewards[association_id] = reward
            
            # Save
            self._save_association(assoc)
            
            print(f"🏆 Association reinforced: creativity {old_creativity:.2f} → {assoc.creativity_score:.2f}")
            
            return True
            
        except Exception as e:
            print(f"⚠️ Association reinforcement error: {e}")
            return False
    
    def get_creative_statistics(self) -> Dict[str, Any]:
        """Get creative associations statistics"""
        try:
            # Association type distribution
            type_dist = defaultdict(int)
            for assoc in self.associations.values():
                type_dist[assoc.association_type.value] += 1
            
            # Creativity level distribution
            level_dist = defaultdict(int)
            for idea in self.creative_ideas:
                level_dist[idea.creativity_level.value] += 1
            
            # Average scores
            if self.associations:
                avg_novelty = np.mean([a.novelty for a in self.associations.values()])
                avg_utility = np.mean([a.utility for a in self.associations.values()])
                avg_creativity = np.mean([a.creativity_score for a in self.associations.values()])
            else:
                avg_novelty = avg_utility = avg_creativity = 0.0
            
            return {
                'total_concepts': len(self.concepts),
                'total_associations': len(self.associations),
                'total_creative_ideas': self.total_creative_ideas,
                'associations_generated': self.total_associations_generated,
                'associations_pruned': self.total_associations_pruned,
                'pruning_rate': self.total_associations_pruned / max(1, self.total_associations_generated),
                'avg_novelty': avg_novelty,
                'avg_utility': avg_utility,
                'avg_creativity': avg_creativity,
                'association_types': dict(type_dist),
                'creativity_levels': dict(level_dist)
            }
            
        except Exception as e:
            print(f"⚠️ Creative statistics error: {e}")
            return {}
    
    def get_recent_creative_ideas(self, limit: int = 5) -> List[CreativeIdea]:
        """Get recent creative ideas"""
        return list(self.creative_ideas)[-limit:]
    
    def _save_concept(self, node: ConceptNode):
        """Save concept to database"""
        try:
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            
            cursor.execute('''
                INSERT OR REPLACE INTO concepts (
                    concept_id, concept, domain, activation, novelty, utility, timestamp
                ) VALUES (?, ?, ?, ?, ?, ?, ?)
            ''', (node.concept_id, node.concept, node.domain, node.activation,
                  node.novelty, node.utility, node.timestamp))
            
            conn.commit()
            conn.close()
            
        except Exception as e:
            print(f"⚠️ Concept save error: {e}")
    
    def _save_association(self, assoc: CreativeAssociation):
        """Save association to database"""
        try:
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            
            cursor.execute('''
                INSERT OR REPLACE INTO associations (
                    association_id, concept_a, concept_b, association_type,
                    strength, novelty, utility, creativity_score, context,
                    timestamp, reinforcement_count, last_reinforcement
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ''', (
                assoc.association_id, assoc.concept_a, assoc.concept_b,
                assoc.association_type.value, assoc.strength, assoc.novelty,
                assoc.utility, assoc.creativity_score, assoc.context,
                assoc.timestamp, assoc.reinforcement_count, assoc.last_reinforcement
            ))
            
            conn.commit()
            conn.close()
            
        except Exception as e:
            print(f"⚠️ Association save error: {e}")
    
    def _save_creative_idea(self, idea: CreativeIdea):
        """Save creative idea to database"""
        try:
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            
            cursor.execute('''
                INSERT INTO creative_ideas (
                    idea_id, idea_content, source_concepts, association_path,
                    creativity_level, novelty_score, utility_score,
                    originality_score, timestamp
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            ''', (
                idea.idea_id, idea.idea_content,
                json.dumps(idea.source_concepts),
                json.dumps(idea.association_path),
                idea.creativity_level.value,
                idea.novelty_score, idea.utility_score,
                idea.originality_score, idea.timestamp
            ))
            
            conn.commit()
            conn.close()
            
        except Exception as e:
            print(f"⚠️ Creative idea save error: {e}")


